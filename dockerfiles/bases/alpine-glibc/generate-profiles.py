#!/usr/bin/env python3
"""Generate skaffold.yaml from matrix.yaml.

Usage:
    yq -o=json matrix.yaml | python3 generate-profiles.py > skaffold.yaml
    make generate

One skaffold artifact (`alpine-glibc`) and one profile per
alpine x glibc combination. Profile patches set the tag, build args,
docker target and platforms.
"""

import json
import sys


def q(value):
    """JSON string is a valid YAML double-quoted scalar."""
    return json.dumps(value, ensure_ascii=False)


def version_key(entry):
    return tuple(int(part) for part in entry["version"].split("."))


def profile_name(alpine, glibc_version):
    return f"alpine-{alpine}_glibc-{glibc_version}"


def build_args(alpine, entry):
    args = [("ALPINE_VERSION", alpine)]
    if entry["target"] == "donor":
        if "donor" not in entry:
            raise SystemExit(f"glibc {entry['version']}: donor target requires 'donor'")
        args.append(("GLIBC_IMAGE", entry["donor"]))
    elif entry["target"] == "apk":
        args.append(("GLIBC_VERSION", entry["version"]))
    else:
        raise SystemExit(f"glibc {entry['version']}: unknown target {entry['target']!r}")
    args.append(("EXTRA_PACKAGES", "tzdata"))
    return args


def platforms(entry):
    value = entry.get("platforms")
    if not isinstance(value, list) or not value:
        raise SystemExit(f"glibc {entry['version']}: platforms must be a non-empty list")
    return value


def emit_artifact(lines, indent, alpine, entry):
    pad = " " * indent
    lines.append(f"{pad}- image: alpine-glibc")
    lines.append(f"{pad}  platforms: [{', '.join(q(p) for p in platforms(entry))}]")
    lines.append(f"{pad}  docker:")
    lines.append(f"{pad}    dockerfile: Dockerfile")
    lines.append(f"{pad}    target: {entry['target']}")
    lines.append(f"{pad}    buildArgs:")
    for key, value in build_args(alpine, entry):
        lines.append(f"{pad}      {key}: {q(value)}")


def emit_profiles(lines, alpines, entries):
    lines.append("profiles:")
    for alpine in alpines:
        for entry in entries:
            name = profile_name(alpine, entry["version"])
            lines.append(f"  - name: {name}")
            lines.append("    patches:")
            lines.append("      - op: replace")
            lines.append("        path: /build/tagPolicy/customTemplate/template")
            lines.append(f"        value: {q(name)}")
            lines.append("      - op: replace")
            lines.append("        path: /build/artifacts/0/docker/target")
            lines.append(f"        value: {q(entry['target'])}")
            lines.append("      - op: replace")
            lines.append("        path: /build/artifacts/0/platforms")
            plats = ", ".join(q(p) for p in platforms(entry))
            lines.append(f"        value: [{plats}]")
            lines.append("      - op: replace")
            lines.append("        path: /build/artifacts/0/docker/buildArgs")
            lines.append("        value:")
            for key, value in build_args(alpine, entry):
                lines.append(f"          {key}: {q(value)}")


def main():
    data = json.load(sys.stdin)
    alpines = data.get("alpine") or []
    entries = data.get("glibc") or []
    if not alpines:
        raise SystemExit("matrix.yaml: 'alpine' must not be empty")
    if not entries:
        raise SystemExit("matrix.yaml: 'glibc' must not be empty")

    entries.sort(key=version_key)
    first_alpine = alpines[0]
    first_entry = entries[0]
    base_name = profile_name(first_alpine, first_entry["version"])

    lines = [
        "# Code generated by generate-profiles.py from matrix.yaml. DO NOT EDIT.",
        "# Run `make generate` after changing matrix.yaml.",
        "---",
        "apiVersion: skaffold/v4beta6",
        "kind: Config",
        "metadata:",
        "  name: alpine-glibc",
        "build:",
        "  artifacts:",
    ]
    emit_artifact(lines, 4, first_alpine, first_entry)
    lines.extend(
        [
            "  tagPolicy:",
            "    customTemplate:",
            f"      template: {q(base_name)}",
            "  local:",
            "    useDockerCLI: true",
            "    useBuildkit: true",
            "    concurrency: 0",
            "    tryImportMissing: true",
        ]
    )
    emit_profiles(lines, alpines, entries)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
